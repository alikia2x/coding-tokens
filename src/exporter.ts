const GENERATED_MARKER = "<!-- generated by harness-token-usage -->";
const MAX_TITLE_LENGTH = 120;

function formatTimestamp(value: number | null): string | null {
	if (value === null || !Number.isFinite(value)) return null;
	const date = new Date(value);
	if (Number.isNaN(date.valueOf())) return null;
	const pad = (part: number) => String(part).padStart(2, "0");
	return `${date.getMonth() + 1}/${date.getDate()} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
}

function roleTag(item: TranscriptItem): string {
	if (item.role === "user") return "USER";
	if (item.role === "assistant") return "ASSISTANT";
	if (item.role === "system") return "SYSTEM";
	if (item.role === "developer") return "DEVELOPER";
	return item.role === "tool" ? "TOOL" : "OTHER";
}

interface TokenTotals {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
	reasoning: number;
	requests: number;
}

function emptyTokenTotals(): TokenTotals {
	return {
		input: 0,
		output: 0,
		cacheRead: 0,
		cacheWrite: 0,
		reasoning: 0,
		requests: 0,
	};
}

function addUsage(totals: TokenTotals, record: UsageRecord): void {
	totals.input += record.inputTokens;
	totals.output += record.outputTokens;
	totals.cacheRead += record.cacheReadTokens;
	totals.cacheWrite += record.cacheWriteTokens;
	totals.reasoning += record.reasoningTokens;
	if (!record.messageId.endsWith(":cumulative-total")) totals.requests += 1;
}

function number(value: number): string {
	return new Intl.NumberFormat("en-US").format(value);
}

function tokenDetails(totals: TokenTotals): string {
	const details = [
		`input ${number(totals.input)}`,
		`output ${number(totals.output)}`,
	];
	if (totals.cacheRead) details.push(`cache read ${number(totals.cacheRead)}`);
	if (totals.cacheWrite)
		details.push(`cache write ${number(totals.cacheWrite)}`);
	if (totals.reasoning) details.push(`reasoning ${number(totals.reasoning)}`);
	if (totals.requests) details.push(`${number(totals.requests)} requests`);
	return details.join(", ");
}

function conversationTokenLine(records: UsageRecord[]): string | null {
	if (!records.length) return null;
	const cumulative = records.filter((record) =>
		record.messageId.endsWith(":cumulative-total"),
	);
	const basis = cumulative.length
		? [cumulative.at(-1) as UsageRecord]
		: records;
	const totals = emptyTokenTotals();
	for (const record of basis) addUsage(totals, record);
	if (cumulative.length)
		totals.requests = records.filter(
			(record) => !record.messageId.endsWith(":cumulative-total"),
		).length;
	return `[TOKENS] ${tokenDetails(totals)}`;
}

function turnForUsage(
	record: UsageRecord,
	users: TranscriptItem[],
	assistantItems: TranscriptItem[],
	knownTurns: ReadonlySet<string>,
): string | undefined {
	if (record.turnId && knownTurns.has(record.turnId)) return record.turnId;
	const timestamp = record.timestamp;
	if (timestamp !== null) {
		let latest: TranscriptItem | undefined;
		for (const user of users) {
			if (user.timestamp !== null && user.timestamp <= timestamp) latest = user;
		}
		if (latest) return latest.turnId;
		const nearestAssistant = closestByTimestamp(assistantItems, timestamp);
		if (nearestAssistant) return nearestAssistant.turnId;
	}
	return assistantItems.at(-1)?.turnId;
}

function closestByTimestamp(
	items: TranscriptItem[],
	timestamp: number | null,
): TranscriptItem | undefined {
	if (!items.length) return undefined;
	if (timestamp === null) return items.at(-1);
	return items.reduce(
		(closest, item) => {
			if (item.timestamp === null) return closest;
			if (!closest || closest.timestamp === null) return item;
			return Math.abs(item.timestamp - timestamp) <
				Math.abs(closest.timestamp - timestamp)
				? item
				: closest;
		},
		undefined as TranscriptItem | undefined,
	);
}

function usageByAssistantMessage(
	session: TranscriptSession,
	detail: ExportDetail,
	visibleItems: TranscriptItem[],
): Map<string, UsageRecord[]> {
	const result = new Map<string, UsageRecord[]>();
	if (detail === "user_only") return result;

	const visibleAssistant = visibleItems.filter(
		(item) => item.kind === "message" && item.role === "assistant",
	);
	if (!visibleAssistant.length) return result;

	const allAssistant = session.items.filter(
		(item) => item.kind === "message" && item.role === "assistant",
	);
	const users = session.items.filter(
		(item) => item.role === "user" && item.kind === "message",
	);
	const knownTurns = new Set(session.items.map((item) => item.turnId));
	const callsByTurn = new Map<string, TranscriptItem[]>();
	for (const item of session.items) {
		if (item.kind !== "tool_call") continue;
		const list = callsByTurn.get(item.turnId) ?? [];
		list.push(item);
		callsByTurn.set(item.turnId, list);
	}

	const append = (item: TranscriptItem | undefined, record: UsageRecord) => {
		if (!item) return;
		const records = result.get(item.id) ?? [];
		records.push(record);
		result.set(item.id, records);
	};

	for (const record of session.usageRecords ?? []) {
		if (record.isSubagent || record.messageId.endsWith(":cumulative-total"))
			continue;
		const turnId = turnForUsage(record, users, allAssistant, knownTurns);
		const sameTurn = visibleAssistant.filter(
			(item) => !turnId || item.turnId === turnId,
		);
		const candidates = sameTurn.length ? sameTurn : visibleAssistant;

		if (detail === "chat_compact") {
			const final = [...candidates]
				.reverse()
				.find((item) => item.phase === "final");
			append(
				final ??
					closestByTimestamp(candidates, record.timestamp) ??
					candidates.at(-1),
				record,
			);
			continue;
		}

		const exact = candidates.find(
			(item) =>
				item.id === record.messageId || item.usageId === record.messageId,
		);
		if (exact) {
			append(exact, record);
			continue;
		}

		const sameTurnCalls = turnId ? (callsByTurn.get(turnId) ?? []) : [];
		const nearestCall = closestByTimestamp(sameTurnCalls, record.timestamp);
		if (
			nearestCall &&
			record.timestamp !== null &&
			nearestCall.timestamp !== null &&
			Math.abs(nearestCall.timestamp - record.timestamp) <= 5_000
		) {
			const afterCall = candidates.find(
				(item) => item.order > nearestCall.order,
			);
			append(
				afterCall ??
					closestByTimestamp(candidates, record.timestamp) ??
					candidates.at(-1),
				record,
			);
			continue;
		}
		append(
			closestByTimestamp(candidates, record.timestamp) ?? candidates.at(-1),
			record,
		);
	}
	return result;
}

function modelTokenLines(records: UsageRecord[]): string[] {
	const byModel = new Map<string, TokenTotals>();
	for (const record of records) {
		const model = record.model || "Unknown model";
		const totals = byModel.get(model) ?? emptyTokenTotals();
		addUsage(totals, record);
		byModel.set(model, totals);
	}
	return [...byModel.entries()].map(
		([model, totals]) => `[MODEL] ${model} | ${tokenDetails(totals)}`,
	);
}

function safeValue(value: unknown): string {
	if (typeof value === "string") return value;
	if (value === undefined) return "(no recorded input/output)";
	try {
		return JSON.stringify(value, null, 2) ?? String(value);
	} catch {
		return String(value);
	}
}

function commandValue(value: unknown): string {
	if (typeof value === "string") return value;
	if (Array.isArray(value) && value.every((item) => typeof item === "string"))
		return value.join("\n");
	if (typeof value === "object" && value !== null) {
		for (const [key, child] of Object.entries(value)) {
			if (/(command|cmd|script)$/iu.test(key) && typeof child === "string")
				return child;
		}
	}
	return safeValue(value);
}

function codeFence(content: string): string {
	const longestRun = Math.max(
		0,
		...(content.match(/`+/gu) ?? []).map((match) => match.length),
	);
	const fence = "`".repeat(Math.max(3, longestRun + 1));
	return `${fence}text\n${content}\n${fence}`;
}

function truncate(value: string, maxLength: number): string {
	if (value.length <= maxLength) return value;
	return `${value.slice(0, maxLength)}\n\n… output shortened …`;
}

function collectPaths(value: unknown): string[] {
	const paths = new Set<string>();
	const visit = (current: unknown, key = "", depth = 0): void => {
		if (depth > 8) return;
		if (typeof current === "string") {
			const normalizedKey = key
				.replaceAll(/([a-z])([A-Z])/gu, "$1_$2")
				.toLowerCase();
			if (
				/(path|paths|file|files|filename|file_name|directory)$/u.test(
					normalizedKey,
				)
			)
				paths.add(current);
			return;
		}
		if (Array.isArray(current)) {
			for (const entry of current) visit(entry, key, depth + 1);
			return;
		}
		if (typeof current !== "object" || current === null) return;
		for (const [childKey, childValue] of Object.entries(current)) {
			if (/^(content|text|output|stdout|stderr)$/iu.test(childKey)) continue;
			visit(childValue, childKey, depth + 1);
		}
	};
	visit(value);
	return [...paths];
}

function agentCallMarkdown(
	item: TranscriptItem,
	detail: ExportDetail,
	includeTimestamps: boolean,
): string {
	const name = item.name ?? "tool";
	const category = item.category ?? "other";
	const timestamp = includeTimestamps ? formatTimestamp(item.timestamp) : null;
	const label = `[TOOL ${name}]${timestamp ? ` (${timestamp})` : ""}${item.status ? ` ${item.status}` : ""}`;
	if (detail === "agent_full") {
		return `${label}\n${codeFence(safeValue(item.input))}`;
	}
	if (category === "command") {
		return `${label} ${commandValue(item.input)}`;
	}
	const paths = collectPaths(item.input);
	if (paths.length)
		return `${label} ${paths.map((value) => `\`${value}\``).join(", ")}`;
	if (item.input !== undefined)
		return `${label}\n${codeFence(truncate(safeValue(item.input), 2_000))}`;
	return label;
}

function resolvedResultName(
	item: TranscriptItem,
	pairedCall?: TranscriptItem,
): string | undefined {
	if (item.name && item.name !== "tool") return item.name;
	return pairedCall?.name ?? item.name;
}

function compactToolMarkdown(
	item: TranscriptItem,
	includeTimestamps: boolean,
): string {
	const operations = normalizeToolOperations(item);
	const timestamp = includeTimestamps ? formatTimestamp(item.timestamp) : null;
	const tsSuffix = timestamp ? ` (${timestamp})` : "";
	if (!operations.length) {
		return agentCallMarkdown(item, "agent", includeTimestamps);
	}
	return operations
		.map((op) => {
			const parts = [`[TOOL ${op.rawName}]${tsSuffix}`];
			if (op.target) parts.push(`\`${op.target}\``);
			if (op.meta) parts.push(`(${op.meta})`);
			return parts.join(" ");
		})
		.join("\n");
}

function toolResultMarkdown(
	item: TranscriptItem,
	detail: ExportDetail,
	includeTimestamps: boolean,
	pairedCall?: TranscriptItem,
): string {
	const timestamp = includeTimestamps ? formatTimestamp(item.timestamp) : null;
	const name = resolvedResultName(item, pairedCall);
	const label = `[TOOL RESULT${name ? ` ${name}` : ""}]${timestamp ? ` (${timestamp})` : ""}${item.status ? ` ${item.status}` : ""}`;
	const unwrapped = unwrapToolOutput(item.output, item.text);
	const body =
		unwrapped !== null
			? unwrapped
			: item.output !== undefined
				? safeValue(item.output)
				: (item.text ?? "");
	if (detail === "agent_full") {
		return body ? `${label}\n${codeFence(body)}` : label;
	}
	return `${label}${body ? `\n${codeFence(truncate(body, 600))}` : ""}`;
}

function renderItem(
	item: TranscriptItem,
	detail: ExportDetail,
	includeTimestamps: boolean,
	usage: UsageRecord[],
	pairedCall?: TranscriptItem,
): string | null {
	const timestamp = includeTimestamps ? formatTimestamp(item.timestamp) : null;
	if (detail === "chat_tools" && item.kind === "tool_call") {
		return compactToolMarkdown(item, includeTimestamps);
	}
	if (item.kind === "tool_call")
		return agentCallMarkdown(item, detail, includeTimestamps);
	if (item.kind === "tool_result")
		return toolResultMarkdown(item, detail, includeTimestamps, pairedCall);
	const body = `[${roleTag(item)}]${timestamp ? ` (${timestamp})` : ""}: ${(item.text ?? "").trimEnd()}`;
	if (item.kind === "message" && item.role === "assistant" && usage.length)
		return `${body}\n\n${modelTokenLines(usage).join("\n")}`;
	return body;
}

function safeSegment(value: string): string {
	const normalized = value
		.normalize("NFKD")
		.replaceAll(/[^\p{L}\p{N}._-]+/gu, "-")
		.replaceAll(/^-+|-+$/gu, "")
		.slice(0, 64);
	return normalized || "unknown";
}

function displayTitle(session: TranscriptSession): string {
	const title = (session.title?.trim() || session.sessionId)
		.replaceAll(/\s+/gu, " ")
		.trim();
	const characters = Array.from(title);
	if (characters.length <= MAX_TITLE_LENGTH) return title;
	return `${characters
		.slice(0, MAX_TITLE_LENGTH - 1)
		.join("")
		.trimEnd()}…`;
}

function markdownLinkLabel(value: string): string {
	return value.replaceAll(/[\\[\]]/gu, "\\$&");
}

function sessionRelativePath(session: TranscriptSession): string {
	const projectName = session.cwd
		? safeBasename(session.cwd)
		: "unknown-project";
	const projectSegment = `${safeSegment(projectName)}-${shaSegment(session.cwd ?? "unknown")}`;
	const sessionSegment = `${safeSegment(session.sessionId)}-${shaSegment(session.sessionId)}`;
	return path.posix.join(
		session.harness,
		projectSegment,
		`${sessionSegment}.md`,
	);
}

export interface RenderSessionOptions {
	detail: ExportDetail;
	includeTimestamps?: boolean;
	includeTokenStats?: boolean;
}

export function renderSessionMarkdown(
	session: TranscriptSession,
	options: RenderSessionOptions,
): string | null {
	return renderSession(
		session,
		options.detail,
		options.includeTimestamps ?? true,
		options.includeTokenStats ?? true,
	);
}

function renderSession(
	session: TranscriptSession,
	detail: ExportDetail,
	includeTimestamps: boolean,
	includeTokenStats: boolean,
): string | null {
	const items = selectItemsForDetail(session, detail);
	if (!items.length) return null;
	const pairedCallByResult = new Map<TranscriptItem, TranscriptItem>();
	for (const pair of pairToolItems(session.items)) {
		if (pair.call.kind !== "tool_call") continue;
		for (const res of pair.results) {
			pairedCallByResult.set(res, pair.call);
		}
	}

	const title = displayTitle(session);
	const lines = [GENERATED_MARKER, `# ${title}`];
	const usageRecords = session.usageRecords ?? [];
	const tokenLine = includeTokenStats
		? conversationTokenLine(usageRecords)
		: null;
	if (tokenLine) lines.push("", tokenLine);
	const usageByMessage = includeTokenStats
		? usageByAssistantMessage(session, detail, items)
		: new Map<string, UsageRecord[]>();
	const renderedItems = items
		.map((item) =>
			renderItem(
				item,
				detail,
				includeTimestamps,
				usageByMessage.get(item.id) ?? [],
				pairedCallByResult.get(item),
			),
		)
		.filter((part): part is string => part !== null);
	if (!renderedItems.length) return null;
	lines.push("", renderedItems.join("\n\n"));
	return `${lines.join("\n").trimEnd()}\n`;
}

function writeGeneratedFile(destination: string, content: string): void {
	if (existsSync(destination)) {
		const current = readFileSync(destination, "utf8");
		if (!current.startsWith(GENERATED_MARKER))
			throw new Error(
				"refusing to overwrite a file not generated by this tool",
			);
	}
	writeFileSync(destination, content, "utf8");
}

function removeStaleGeneratedFiles(
	outputDirectory: string,
	expectedFiles: Set<string>,
	warnings: string[],
): number {
	let removed = 0;
	const visit = (directory: string): void => {
		for (const entry of readdirSync(directory, { withFileTypes: true })) {
			const filePath = path.join(directory, entry.name);
			if (entry.isDirectory()) {
				visit(filePath);
				continue;
			}
			if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
			if (expectedFiles.has(path.resolve(filePath))) continue;
			try {
				if (!readFileSync(filePath, "utf8").startsWith(GENERATED_MARKER))
					continue;
				unlinkSync(filePath);
				removed += 1;
			} catch (error) {
				warnings.push(
					`Failed to remove stale generated file ${filePath} (${String(error)})`,
				);
			}
		}
	};
	visit(outputDirectory);
	return removed;
}

export function exportSessionsToMarkdown(
	sessions: TranscriptSession[],
	options: MarkdownExportOptions,
): MarkdownExportResult {
	const warnings: string[] = [];
	const outputDirectory = path.resolve(options.outputDirectory);
	try {
		mkdirSync(outputDirectory, { recursive: true });
	} catch (error) {
		return {
			filesWritten: 0,
			filesRemoved: 0,
			indexPath: path.join(outputDirectory, "_index.md"),
			warnings: [`Failed to create ${outputDirectory} (${String(error)})`],
		};
	}
	const indexEntries: string[] = [];
	const expectedFiles = new Set<string>();
	let filesWritten = 0;
	for (const session of sessions) {
		const content = renderSession(
			session,
			options.detail,
			options.includeTimestamps,
			options.includeTokenStats,
		);
		if (!content) continue;
		const relative = sessionRelativePath(session);
		const destination = path.join(outputDirectory, relative);
		expectedFiles.add(path.resolve(destination));
		try {
			mkdirSync(path.dirname(destination), { recursive: true });
			writeGeneratedFile(destination, content);
			filesWritten += 1;
			indexEntries.push(
				`- [${markdownLinkLabel(displayTitle(session))}](${relative})`,
			);
		} catch (error) {
			warnings.push(`Failed to write ${destination} (${String(error)})`);
		}
	}
	const indexPath = path.join(outputDirectory, "_index.md");
	expectedFiles.add(path.resolve(indexPath));
	const index = [
		GENERATED_MARKER,
		"# Conversations",
		"",
		...(indexEntries.length ? indexEntries : ["No matching sessions found."]),
		"",
	].join("\n");
	try {
		writeGeneratedFile(indexPath, index);
	} catch (error) {
		warnings.push(`Failed to write ${indexPath} (${String(error)})`);
	}
	const filesRemoved = warnings.length
		? 0
		: removeStaleGeneratedFiles(outputDirectory, expectedFiles, warnings);
	return { filesWritten, filesRemoved, indexPath, warnings };
}

const CRC32_TABLE = (() => {
	const table = new Uint32Array(256);
	for (let i = 0; i < 256; i += 1) {
		let c = i;
		for (let bit = 0; bit < 8; bit += 1) {
			c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
		}
		table[i] = c >>> 0;
	}
	return table;
})();

function crc32(data: Uint8Array): number {
	let crc = 0xffffffff;
	for (let i = 0; i < data.length; i += 1) {
		crc = (CRC32_TABLE[(crc ^ (data[i] ?? 0)) & 0xff] ?? 0) ^ (crc >>> 8);
	}
	return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Packages flat or relative entries into a standard PKZIP archive (deflate).
 */
export function createZipArchive(
	entries: ReadonlyArray<{ name: string; content: string | Uint8Array }>,
): Uint8Array {
	const encoder = new TextEncoder();
	const now = new Date();
	const dosTime =
		((now.getHours() & 0x1f) << 11) |
		((now.getMinutes() & 0x3f) << 5) |
		((now.getSeconds() >> 1) & 0x1f);
	const dosDate =
		(((Math.max(1980, now.getFullYear()) - 1980) & 0x7f) << 9) |
		(((now.getMonth() + 1) & 0x0f) << 5) |
		(now.getDate() & 0x1f);

	const localParts: Buffer[] = [];
	const centralParts: Buffer[] = [];
	let offset = 0;

	for (const entry of entries) {
		const nameBytes = Buffer.from(encoder.encode(entry.name));
		const rawBytes =
			typeof entry.content === "string"
				? Buffer.from(encoder.encode(entry.content))
				: Buffer.from(entry.content);
		const compressed = Buffer.from(deflateRawSync(rawBytes));
		const useDeflate = compressed.length < rawBytes.length;
		const payload = useDeflate ? compressed : rawBytes;
		const method = useDeflate ? 8 : 0;
		const crc = crc32(rawBytes);

		const localHeader = Buffer.alloc(30);
		localHeader.writeUInt32LE(0x04034b50, 0);
		localHeader.writeUInt16LE(20, 4);
		localHeader.writeUInt16LE(0x0800, 6); // UTF-8 filename flag
		localHeader.writeUInt16LE(method, 8);
		localHeader.writeUInt16LE(dosTime, 10);
		localHeader.writeUInt16LE(dosDate, 12);
		localHeader.writeUInt32LE(crc, 14);
		localHeader.writeUInt32LE(payload.length, 18);
		localHeader.writeUInt32LE(rawBytes.length, 22);
		localHeader.writeUInt16LE(nameBytes.length, 26);
		localHeader.writeUInt16LE(0, 28);

		localParts.push(localHeader, nameBytes, payload);

		const centralHeader = Buffer.alloc(46);
		centralHeader.writeUInt32LE(0x02014b50, 0);
		centralHeader.writeUInt16LE(20, 4);
		centralHeader.writeUInt16LE(20, 6);
		centralHeader.writeUInt16LE(0x0800, 8);
		centralHeader.writeUInt16LE(method, 10);
		centralHeader.writeUInt16LE(dosTime, 12);
		centralHeader.writeUInt16LE(dosDate, 14);
		centralHeader.writeUInt32LE(crc, 16);
		centralHeader.writeUInt32LE(payload.length, 20);
		centralHeader.writeUInt32LE(rawBytes.length, 24);
		centralHeader.writeUInt16LE(nameBytes.length, 28);
		centralHeader.writeUInt16LE(0, 30);
		centralHeader.writeUInt16LE(0, 32);
		centralHeader.writeUInt16LE(0, 34);
		centralHeader.writeUInt16LE(0, 36);
		centralHeader.writeUInt32LE(0, 38);
		centralHeader.writeUInt32LE(offset, 42);

		centralParts.push(centralHeader, nameBytes);
		offset += localHeader.length + nameBytes.length + payload.length;
	}

	const centralSize = centralParts.reduce((sum, part) => sum + part.length, 0);
	const eocd = Buffer.alloc(22);
	eocd.writeUInt32LE(0x06054b50, 0);
	eocd.writeUInt16LE(0, 4);
	eocd.writeUInt16LE(0, 6);
	eocd.writeUInt16LE(entries.length, 8);
	eocd.writeUInt16LE(entries.length, 10);
	eocd.writeUInt32LE(centralSize, 12);
	eocd.writeUInt32LE(offset, 16);
	eocd.writeUInt16LE(0, 20);

	return Buffer.concat([...localParts, ...centralParts, eocd]);
}
